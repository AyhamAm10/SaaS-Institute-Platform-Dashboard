import { useMutation, useQuery, useQueryClient } from '@tanstack/react-query';
import { apiClient } from './client';
import { SafeUser } from './types';

export interface InstituteAdminUser {
  id: number;
  fullName: string;
  phone: string;
  role: string;
}

export interface InstituteAdminLink {
  user: InstituteAdminUser;
}

export interface InstituteCount {
  users: number;
  branches: number;
  sections: number;
  students: number;
}

export interface Institute {
  id: number;
  /** Login code users enter when their phone exists in several institutes. */
  code: string;
  name: string;
  logoUrl?: string;
  primaryColor?: string;
  secondaryColor?: string;
  phone: string;
  address: string;
  createdAt: string;
  updatedAt: string;
  instituteAdmins?: InstituteAdminLink[];
  _count?: InstituteCount;
}

export interface CreateInstitutePayload {
  name: string;
  /** Optional — generated by the backend when omitted. */
  code?: string;
  logoUrl?: string;
  primaryColor?: string;
  secondaryColor?: string;
  phone: string;
  address: string;
  adminFullName: string;
  adminPhone: string;
  adminPassword: string;
}

/** Editable institute details (the initial admin account is creation-only). */
export type UpdateInstitutePayload = Partial<
  Omit<CreateInstitutePayload, 'adminFullName' | 'adminPhone' | 'adminPassword'>
>;

/** Optional modules an institute can switch on. */
export type FeatureKey =
  | 'SMS'
  | 'ONLINE_REGISTRATION'
  | 'PARENTS_APP'
  | 'STUDENTS_APP'
  | 'ACCOUNTING';

export interface FeatureStatus {
  key: FeatureKey;
  enabled: boolean;
}

export interface InstituteWithAdminResponse {
  institute: Institute;
  admin: SafeUser;
}

export interface PaginatedInstitutes {
  data: Institute[];
  total: number;
  page: number;
  limit: number;
  totalPages: number;
}

export interface InstitutesQueryParams {
  page?: number;
  limit?: number;
  search?: string;
}

// --------------------------------------------------------------------------
// API Functions
// --------------------------------------------------------------------------

export async function getInstitutes(
  params?: InstitutesQueryParams,
): Promise<PaginatedInstitutes> {
  const { data } = await apiClient.get<PaginatedInstitutes>('/institutes', {
    params,
  });
  return data;
}

export async function getInstituteById(id: number): Promise<Institute> {
  const { data } = await apiClient.get<Institute>(`/institutes/${id}`);
  return data;
}

export async function createInstitute(
  payload: CreateInstitutePayload,
): Promise<InstituteWithAdminResponse> {
  const { data } = await apiClient.post<InstituteWithAdminResponse>(
    '/institutes',
    payload,
  );
  return data;
}

export async function updateInstitute(
  id: number,
  payload: UpdateInstitutePayload,
): Promise<Institute> {
  const { data } = await apiClient.patch<Institute>(`/institutes/${id}`, payload);
  return data;
}

export async function getInstituteFeatures(id: number): Promise<FeatureStatus[]> {
  const { data } = await apiClient.get<FeatureStatus[]>(`/institutes/${id}/features`);
  return data;
}

export async function updateInstituteFeatures(
  id: number,
  features: FeatureStatus[],
): Promise<FeatureStatus[]> {
  const { data } = await apiClient.put<FeatureStatus[]>(`/institutes/${id}/features`, {
    features,
  });
  return data;
}

// --------------------------------------------------------------------------
// React Query Keys
// --------------------------------------------------------------------------

export const INSTITUTES_QUERY_KEYS = {
  all: ['institutes'] as const,
  list: (params?: InstitutesQueryParams) =>
    ['institutes', 'list', params] as const,
  detail: (id: number) => ['institutes', 'detail', id] as const,
  features: (id: number) => ['institutes', 'features', id] as const,
};

// --------------------------------------------------------------------------
// React Query Hooks
// --------------------------------------------------------------------------

export function useInstitutesQuery(params?: InstitutesQueryParams) {
  return useQuery({
    queryKey: INSTITUTES_QUERY_KEYS.list(params),
    queryFn: () => getInstitutes(params),
    staleTime: 30 * 1000,
  });
}

export function useInstituteDetailsQuery(id: number | null, enabled = true) {
  return useQuery({
    queryKey: id ? INSTITUTES_QUERY_KEYS.detail(id) : ['institutes', 'detail', 'null'],
    queryFn: () => (id ? getInstituteById(id) : Promise.reject('No ID provided')),
    enabled: Boolean(id) && enabled,
    staleTime: 60 * 1000,
  });
}

export function useCreateInstituteMutation() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: (payload: CreateInstitutePayload) => createInstitute(payload),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: INSTITUTES_QUERY_KEYS.all });
    },
  });
}

export function useUpdateInstituteMutation() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: ({ id, payload }: { id: number; payload: UpdateInstitutePayload }) =>
      updateInstitute(id, payload),
    onSuccess: () => {
      queryClient.invalidateQueries({ queryKey: INSTITUTES_QUERY_KEYS.all });
    },
  });
}

export function useInstituteFeaturesQuery(id: number | null) {
  return useQuery({
    queryKey: INSTITUTES_QUERY_KEYS.features(id ?? 0),
    queryFn: () => getInstituteFeatures(id!),
    enabled: Boolean(id),
  });
}

export function useUpdateInstituteFeaturesMutation() {
  const queryClient = useQueryClient();

  return useMutation({
    mutationFn: ({ id, features }: { id: number; features: FeatureStatus[] }) =>
      updateInstituteFeatures(id, features),
    onSuccess: (data, { id }) => {
      queryClient.setQueryData(INSTITUTES_QUERY_KEYS.features(id), data);
    },
  });
}
